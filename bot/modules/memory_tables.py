# The reply that says the fact is not there: after a guess it must not claim they never said it.
ELIDED_NOT_SURE = re.compile(r"\bhaven't (?:told|mentioned)\b|\bdon't know (?:it|your)\b")
# The ask's own words narrow which fact it can be about. "and what did I call him?" names a name,
# so the fact they told me just before is only the answer if it was a name or a pet: "I live in
