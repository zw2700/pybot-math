# "how many cats" is the same ask as "how many cats do i have": the count they gave is the answer,
# and the words that make it a question about them ("do i have", "have i got", "are there") are
# often left off. A line that asks how many of something else ("how many cats should i get") is a
# question about the world, so only a line that ends at the number is read here.
COUNT_ANIMAL = re.compile(
    r"^\s*(?:ok |okay |so |and |but |well |oh |quick |just )*how many\s+"
    r"(dogs?|cats?|puppies|puppy|kittens?|kitten|rabbits?|bunnies|bunny|hamsters?|fish|horses?|"
    r"ponies|parrots?|pets?)\b\s*"
    r"(?:do (?:i|we) have|have (?:i|we) got|did (?:i|we) say|do (?:i|we) own|have we|"
    r"are there|(?:is|was|are|were) (?:that|it|this)(?: again| now)?|again|then|now)?"
    r"\s*[?.!]*\s*$", re.I)
# "how many do i have" names none of them: the count of the one animal they have is the answer,
# and it is only used when the store holds exactly one kind.
COUNT_BARE = re.compile(
    r"^\s*(?:ok |okay |so |and |but |well |oh |quick |just )*how many\s+"
    r"(?:do (?:i|we) have|have (?:i|we) got|do (?:i|we) own|are there|did (?:i|we) say|"
    r"in total|altogether)?\s*[?.!]*\s*$", re.I)

# "What did I just say?" is the person's own last line, but only when the ask ends there:
# "what did I say my budget was again?" is a fact recall and belongs to the store's own keys.
# The recency can sit in a noun phrase instead of an adverb ("what was the last thing i said"),
# which is the same ask about the same line.
# "what did i say about the cake", "what did i just tell you about my mum": the ask for something
# the person has already said. "just" is emphasis, not a subject, so it sits between the two words
# without changing the ask - read as anything else, "what did i just tell you" was answered as a
# question about the bot itself ("I'm a chatbot - here to help and chat").
WHAT_I_SAID = re.compile(
    r"\bwhat did i (?:just )?(?:say|tell you|mention)\b|\bwhat have i (?:said|mentioned)\b")

