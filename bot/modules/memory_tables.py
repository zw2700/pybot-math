# An ask that leaves the fact out because it was just named: "what did I say it was again?",
# "and what did I call him?". It is answered about the fact the last recall question asked
# about (memory["asked"]), so the store needs no second copy of the fact's patterns.
ELIDED_ASK = re.compile(
    r"\bwhat (?:did|do) i (?:say|call|name) (?:it|him|her|them|they|he|she)"
    r"(?: (?:was|were|is|are))?(?: (?:called|named))?\b"
    r"|\b(?:and )?what (?:was|is) (?:it|that) again\b"
    r"|\b(?:and )?(?:what|which) (?:was|is) (?:its |his |her |their |the )?name(?: again)?\b"
    r"|\b(?:and )?what did i (?:call|name) (?:him|her|them)\b"
    r"|\bwhat (?:was|is) that called again\b")
# "and where was that again?" is the same ask, but only with its "again": "where is that?" is a
# question about the place itself, and the folded line no longer carries the word.
ELIDED_AGAIN = re.compile(r"\b(?:where|when) (?:was|is) (?:it|that|that one)\b")
# Words that only point back at the last ask: a line with anything else in it is about that
